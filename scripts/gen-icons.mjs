// Generates src/components/icon-paths.ts from @material-symbols/svg-400 (Apache-2.0).
// Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const ICONS = [
  "work",
  "air",
  "foggy",
  "thunderstorm",
  "sunny",
  "home",
  "home-fill",
  "rainy",
  "rainy-fill",
  "history",
  "settings",
  "settings-fill",
  "refresh",
  "directions_car",
  "two_wheeler",
  "question_mark",
  "warning",
  "water_drop",
  "location_on",
  "wifi_off",
  "event_busy",
  "partly_cloudy_day",
  "rainy_light",
  "rainy_heavy",
  "cloud",
  "schedule",
];

const base = "node_modules/@material-symbols/svg-400/outlined";
const entries = ICONS.map((name) => {
  const svg = readFileSync(`${base}/${name}.svg`, "utf8");
  const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1)
    throw new Error(`${name}: expected 1 path, got ${paths.length}`);
  const key = name.replace(/[-_](\w)/g, (_, c) => c.toUpperCase());
  return `  ${key}: "${paths[0]}",`;
});

writeFileSync(
  "src/components/icon-paths.ts",
  `// Generated by scripts/gen-icons.mjs from Material Symbols (Apache-2.0). Do not edit.\n` +
    `// viewBox: 0 -960 960 960, weight 400, outlined.\n` +
    `export const iconPaths = {\n${entries.join("\n")}\n} as const;\n\n` +
    `export type IconName = keyof typeof iconPaths;\n`,
);
console.log(`wrote ${ICONS.length} icons`);
